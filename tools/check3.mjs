// Case 4 videos, lightbox video + 4× images, footer glass. Run with the server up: node tools/check3.mjs
import puppeteer from 'puppeteer-core';
const B = 'http://localhost:3000', SH = new URL('./.shots/', import.meta.url).pathname;
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage(); await p.setViewport({ width: 1280, height: 800 });
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const ok = (n, v) => console.log(v ? '✓' : '✗', n);
await p.goto(B + '/work/ai-background-removal/', { waitUntil: 'networkidle0' });
await p.evaluate(() => document.querySelector('video[data-lb]').scrollIntoView({ block: 'center', behavior: 'instant' })); await wait(1500);
ok('video plays on screen', await p.evaluate(() => { const v = document.querySelector('video[data-lb]'); return !v.paused && v.currentTime > 0; }));
ok('video ' + await p.evaluate(() => document.querySelector('video[data-lb]').currentSrc.split('/').pop()), true);
await p.evaluate(() => document.querySelector('video[data-lb]').click()); await wait(800);
ok('video opens in lightbox ' + await p.evaluate(() => document.querySelector('.lb-cnt').textContent), await p.evaluate(() => { const v = document.querySelector('.lb-vid'); return !v.hidden && !v.paused && document.querySelector('.lb-img').hidden; }));
await p.screenshot({ path: SH + 'lb-video.png' });
await p.keyboard.press('ArrowRight'); await wait(600);
ok('item 3 is the second video', await p.evaluate(() => !document.querySelector('.lb-vid').hidden));
await p.keyboard.press('ArrowRight'); await wait(600);
ok('item 4 is an image again', await p.evaluate(() => !document.querySelector('.lb-img').hidden && document.querySelector('.lb-vid').hidden));
await p.keyboard.press('Escape');
await p.goto(B + '/work/app-rebrand-design-system/', { waitUntil: 'networkidle0' });
const n = await p.evaluate(() => [...document.querySelectorAll('img[width="600"]')].findIndex((i) => i.dataset.full));
await p.evaluate((n) => document.querySelectorAll('img[width="600"]')[n].click(), n); await wait(2000);
ok('lightbox shows 4× file: ' + await p.evaluate(() => document.querySelector('.lb-img').src.split('/').pop() + ' ' + document.querySelector('.lb-img').naturalWidth + 'px'), await p.evaluate(() => /@full/.test(document.querySelector('.lb-img').src) && document.querySelector('.lb-img').naturalWidth === 2400));
await p.keyboard.press('Escape'); await wait(300);
ok('glass on footer box', await p.evaluate(() => /lgF1/.test(document.querySelector('.foot-wrap').style.filter)));
const H = await p.evaluate(() => document.documentElement.scrollHeight);
await p.evaluate((H) => scrollTo({ top: H - 800 - 120, behavior: 'instant' }), H); await wait(700);
await p.screenshot({ path: SH + 'glass-foot.png', clip: { x: 0, y: 600, width: 1280, height: 200 } });
ok('no JS errors ' + errs.join(' | '), !errs.length);
await b.close();
